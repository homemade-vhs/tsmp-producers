// Bundles font files into assets/fonts/bundled-fonts.js so they load with the page on any machine — opened from
// disk (file://, where a page can't read a folder or fetch files) or hosted — with no "Choose fonts folder" step.
//
//   node tools/bundle-fonts.mjs                       # the default list below
//   node tools/bundle-fonts.mjs "pixel fonts/Foo.ttf"  # paths relative to assets/fonts
//
// Only bundle fonts you're allowed to redistribute: if the tool is hosted publicly, anyone can download them.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FONTS = path.join(ROOT, 'assets', 'fonts');
const DEFAULT_LIST = ['pixel fonts/PrevueGrid-Pixelated.ttf', 'pixel fonts/PrevueGrid.ttf', 'pixel fonts/PrevueList.ttf'];

const list = process.argv.length > 2 ? process.argv.slice(2) : DEFAULT_LIST;
const fonts = list.map((rel) => {
  const file = path.join(FONTS, rel);
  const data = fs.readFileSync(file);
  // id = path relative to assets/fonts, the same id a "Choose fonts folder" scan gives it, so saved settings match either way
  return { id: rel.split(path.sep).join('/'), size: data.length, data: data.toString('base64') };
});

const out = `// Generated by tools/bundle-fonts.mjs — don't edit by hand; re-run the script to change the list.
// Fonts registered with the page at startup (before layout), so they work on any machine.
window.TVGUIDE_BUNDLED_FONTS = ${JSON.stringify(fonts)};
`;
fs.writeFileSync(path.join(FONTS, 'bundled-fonts.js'), out);
console.log(`Bundled ${fonts.length} font(s), ${Math.round(out.length / 1024)} KB → assets/fonts/bundled-fonts.js`);
for (const f of fonts) console.log(`  ${f.id} (${Math.round(f.size / 1024)} KB)`);
